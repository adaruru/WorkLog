const I18N = {
  lang: 'zh-TW',

  set(lang) {
    this.lang = DICT[lang] ? lang : 'zh-TW';
    document.documentElement.lang = this.lang;
  },

  t(key, vars) {
    const table = DICT[this.lang] || DICT['zh-TW'];
    let text = table[key] ?? DICT['zh-TW'][key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replaceAll(`{${name}}`, value);
      }
    }
    return text;
  },

  apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((node) => {
      node.textContent = this.t(node.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
      node.placeholder = this.t(node.dataset.i18nPlaceholder);
    });
    root.querySelectorAll('[data-i18n-title]').forEach((node) => {
      node.title = this.t(node.dataset.i18nTitle);
    });
  }
};

window.I18N = I18N;
